async function main() {
  const idx: Record<string, { definition: string; phonetic?: string }> = {};

  // 1. Seed core children's dictionary
  for (const [k, v] of Object.entries(CORE_CHILDREN_DICTIONARY)) {
    const cleanKey = k.replace(/_v$|_adv$/, '');
    idx[cleanKey] = { definition: v };
  }

  // 2. Seed all vocabulary activities from PILOT_STORIES
  for (const s of PILOT_STORIES) {
    for (const a of s.activities) {
      if (a.type === 'vocabulary' && 'word' in a && 'definition' in a) {
        const k = clean((a as any).word);
        if (k) idx[k] = { definition: (a as any).definition };
      }
    }
  }

  // 3. Seed all story glossaries from PILOT_STORIES
  for (const s of PILOT_STORIES) {
    for (const g of s.glossary) {
      const k = clean(g.word);
      if (k) idx[k] = { definition: g.definition, phonetic: idx[k]?.phonetic };
    }
  }

  // 4. Seed all GHANAIAN_PRONUNCIATIONS (preserving glossary definition if already richer, adding phonetic)
  for (const e of GHANAIAN_PRONUNCIATIONS.entries) {
    const k = clean(e.written);
    const br = e.engines.browser;
    const ph = br && 'text' in br ? br.text : undefined;
    const rawMeaning = e.meaning ?? e.guidance;
    const def = rawMeaning.endsWith('.') ? rawMeaning : `${rawMeaning}.`;
    if (k) {
      idx[k] = {
        definition: idx[k]?.definition ? `${idx[k].definition} (${def})` : def,
        phonetic: ph,
      };
    }
    const idK = clean(e.id);
    if (idK && !idx[idK]) {
      idx[idK] = { definition: def, phonetic: ph };
    }
  }

  const outPath = path.resolve(process.cwd(), 'src/lib/story-library/story-glossary-index.json');
  fs.writeFileSync(outPath, JSON.stringify(idx, null, 2));
  console.log('Wrote story-glossary-index.json with', Object.keys(idx).length, 'entries');
}

main();
